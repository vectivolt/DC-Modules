#!/usr/bin/env node
// lcsc-from-build.mjs — harvest LCSC part numbers that the tscircuit build already resolved, and
// emit them as LCSC_BY_VALUE entries keyed on `family|value`.
//
// The build carries `supplier_part_numbers.jlcpcb` per component: tscircuit matched the value and
// package against the JLC catalogue. That is a better source than hand lookups for ordinary
// passives, and it covers the long tail that would otherwise take one search each.
//
// It is NOT safe for every family. tscircuit matches value and package; it does not know that a
// resistor must be 0.5 W because it takes a gate-drive pulse, or that a cap must carry an X1/Y1
// safety certification, or that a divider must be 0.1%. Adopting its answer for those would
// repeat exactly the mistake that made RC1206FR-074R7L (250 mW) look like a valid gate resistor.
// So only families whose class is a VALUE class, not a RATING class, are harvested.
//
// Run: node calculations/cost/lcsc-from-build.mjs   (prints entries to paste, or --write)

import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DB } from "./parts-db.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

// Families where value+package fully determines the part. Everything absent from this list is
// rating-, tolerance- or certification-defined and must stay CLASS until someone chooses a part.
const VALUE_CLASS = new Set([
  "R-small", "MLCC-small", "R1206-33R-1%", "MLCC-1u-0805", "MLCC-100p-0603",
  "MLCC-100n-0402", "R0805-10k", "R0603-220", "EL-220u-35", "IND-10u-3A",
]);

const eng = (x, unit) => {
  if (!(x > 0)) return "";
  const p = [[1e6, "M"], [1e3, "k"], [1, ""], [1e-3, "m"], [1e-6, "u"], [1e-9, "n"], [1e-12, "p"]];
  for (const [m, s] of p) if (x >= m * 0.9999) return `${Number((x / m).toPrecision(3))}${s}${unit}`;
  return `${x}${unit}`;
};
const valueOf = (c) => c.ftype === "simple_resistor"
  ? (Number(c.resistance) === 0 ? "0R" : eng(Number(c.resistance), ""))
  : c.ftype === "simple_capacitor" ? eng(Number(c.capacitance), "F") : "";

const votes = new Map();          // family|value -> Map(lcsc -> count)
for (const sku of ["30kw", "60kw", "120kw"]) {
  for (const side of ["acdc", "dcdc"]) {
    const p = join(ROOT, "dist/boards", sku, side, "circuit.json");
    if (!existsSync(p)) continue;
    for (const c of JSON.parse(readFileSync(p, "utf8"))) {
      if (c.type !== "source_component") continue;
      const lcsc = (c.supplier_part_numbers ?? {}).jlcpcb?.[0];
      if (!lcsc) continue;
      const rule = DB.find((r) => r.m.test(c.name));
      if (!rule || !VALUE_CLASS.has(rule.mpn)) continue;
      const v = valueOf(c);
      if (!v) continue;
      const k = `${rule.mpn}|${v}`;
      if (!votes.has(k)) votes.set(k, new Map());
      const m = votes.get(k);
      m.set(lcsc, (m.get(lcsc) ?? 0) + 1);
    }
  }
}

const rows = [], conflicts = [];
for (const [k, m] of [...votes].sort()) {
  const sorted = [...m].sort((a, b) => b[1] - a[1]);
  if (sorted.length > 1) conflicts.push(`${k}: ${sorted.map(([l, n]) => `${l}x${n}`).join(" ")}`);
  rows.push({ k, lcsc: sorted[0][0], n: sorted.reduce((a, [, n]) => a + n, 0) });
}

console.log(`${rows.length} family|value pairs resolved from the build, covering ${rows.reduce((a, r) => a + r.n, 0)} components`);
if (conflicts.length) {
  console.log(`\n${conflicts.length} pair(s) where the build gave more than one part — most common wins, listed for review:`);
  conflicts.forEach((c) => console.log("   " + c));
}
const block = rows.map((r) =>
  `  ${JSON.stringify(r.k).padEnd(26)} { lcsc: ${JSON.stringify(r.lcsc).padEnd(12)} note: "from the tscircuit build (${r.n}x)" },`).join("\n");

if (process.argv.includes("--write")) {
  const p = join(ROOT, "calculations/cost/lcsc-by-value-generated.mjs");
  writeFileSync(p, `// GENERATED by calculations/cost/lcsc-from-build.mjs — do not hand-edit.\n`
    + `// LCSC numbers the tscircuit build already resolved, for families where value+package\n`
    + `// fully determines the part. Rating/tolerance/certification-defined families are excluded\n`
    + `// by VALUE_CLASS in the generator and stay CLASS deliberately.\n`
    + `export const LCSC_FROM_BUILD = {\n${block}\n};\n`);
  console.log(`\n-> ${p}`);
} else {
  console.log("\n" + block);
}
