#!/usr/bin/env node
// pin-map-export.mjs — publish the symbol→package pin map.
//
// The design is authored with LOGICAL pin identifiers (G/D/S/KS, VIA/PWM/KSRC, ...) and a
// remap in easyeda-apply-gen.mjs translates them to PHYSICAL package pins before any netlist
// leaves the repo. That remap was never published, so a reviewer reading only the rendered
// drawing sees logical numbering and cannot tell it from a wrong pinout — exactly the
// objection raised in the external 30/60/120 kW review.
//
// This emits the mapping as a reviewable artefact, joining the logical pins in the built
// circuit.json against the physical pins in the apply payloads.
//
// Output: docs/symbol-pin-map.md + calculations/out/symbol-pin-map.csv
// Run:    node calculations/pin-map-export.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LCSC } from "./cost/lcsc-map.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const APPLY = join(ROOT, "calculations/out/easyeda/apply");

// physical: designator -> [{num,name}] from the apply payloads
const phys = new Map(), mpnOf = new Map();
for (const f of readdirSync(APPLY).filter((x) => x.endsWith(".json"))) {
  for (const c of JSON.parse(readFileSync(join(APPLY, f), "utf8")).chunks.flat()) {
    phys.set(c.designator, c.pins.map((p) => ({ num: String(p.pin_number), name: p.name })));
    mpnOf.set(c.designator, c.mpn || c.value);
  }
}
// logical: designator -> [{num,name}] from the built netlist
const logi = new Map();
for (const side of ["acdc", "dcdc"]) {
  const j = JSON.parse(readFileSync(join(ROOT, "dist/boards/30kw", side, "circuit.json"), "utf8"));
  const nm = new Map(j.filter((e) => e.type === "source_component").map((c) => [c.source_component_id, c.name]));
  for (const p of j.filter((e) => e.type === "source_port")) {
    const d = nm.get(p.source_component_id);
    if (!logi.has(d)) logi.set(d, []);
    logi.get(d).push({ num: String(p.pin_number), name: p.name });
  }
}

// one row per part FAMILY (first designator that uses it)
const fams = new Map();
for (const [d, pins] of phys) {
  const m = mpnOf.get(d);
  if (!fams.has(m) && logi.has(d)) fams.set(m, { d, physical: pins, logical: logi.get(d) });
}

const rows = [];
const md = [`# Symbol → package pin map (verified)

The schematic is authored with **logical** pin identifiers — \`G\`/\`D\`/\`S\`/\`KS\` on a MOSFET,
\`VIA\`/\`PWM\`/\`KSRC\` on a gate driver — because the cells are SKU-generic. Every netlist that
leaves this repo is emitted through the remap in
[\`calculations/easyeda-apply-gen.mjs\`](../calculations/easyeda-apply-gen.mjs), which
translates those identifiers to **physical package pins** taken from the manufacturer datasheet.

**This table is that mapping.** Rendered drawings that show logical numbering are not a pinout
error; they are a drawing that has not applied the map. The KiCad output
(\`kicad5/\`, \`kicad/\`) and the EasyEDA payloads carry the physical numbering below and are
verified pin-by-pin against the design intent (\`calculations/kicad5-verify.mjs\`, 1724/1724).

Generated by \`calculations/pin-map-export.mjs\` — do not hand-edit.

| Part | Example ref | Logical (as drawn) | Physical (as built) | LCSC |
|---|---|---|---|---|`];

for (const [m, v] of [...fams].sort()) {
  const lmap = new Map(v.logical.map((p) => [p.name, p.num]));
  const same = v.physical.every((p) => lmap.get(p.name) === p.num);
  const L = v.physical.map((p) => `${lmap.get(p.name) ?? "-"}=${p.name}`).join(" ");
  const P = v.physical.map((p) => `${p.num}=${p.name}`).join(" ");
  const lc = LCSC[m] ?? {};
  md.push(`| \`${m}\` | ${v.d} | ${same ? "_(same)_" : L} | ${P} | ${lc.lcsc ?? lc.status ?? ""} |`);
  for (const p of v.physical) rows.push([m, v.d, p.name, lmap.get(p.name) ?? "", p.num, lc.lcsc ?? lc.status ?? ""]);
}

const remapped = [...fams].filter(([, v]) => {
  const lmap = new Map(v.logical.map((p) => [p.name, p.num]));
  return !v.physical.every((p) => lmap.get(p.name) === p.num);
}).length;
md.splice(1, 0, `\n**${fams.size} part families · ${remapped} carry a logical→physical remap · ${rows.length} pins.**\n`);

writeFileSync(join(ROOT, "docs/symbol-pin-map.md"), md.join("\n") + "\n");
writeFileSync(join(ROOT, "calculations/out/symbol-pin-map.csv"),
  "part,example_ref,pin_name,logical_pin,physical_pin,lcsc\n" + rows.map((r) => r.join(",")).join("\n") + "\n");
console.log(`${fams.size} families · ${remapped} remapped · ${rows.length} pins → docs/symbol-pin-map.md`);
