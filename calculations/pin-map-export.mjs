#!/usr/bin/env node
// pin-map-export.mjs — publish the symbol→package pin map.
//
// The design is authored with LOGICAL pin identifiers (G/D/S/KS, DST/ASC/RDY, ...) and a
// remap in sheet-netlist-gen.mjs translates them to PHYSICAL package pins before any netlist
// leaves the repo. That remap was never published, so a reviewer reading only the rendered
// drawing sees logical numbering and cannot tell it from a wrong pinout — exactly the
// objection raised in the external 30/60/120 kW review.
//
// This emits the mapping as a reviewable artefact, joining the logical pins in the built
// circuit.json against the physical pins in the apply payloads.
//
// Output: docs/symbol-pin-map.md + calculations/out/symbol-pin-map.csv
// Run:    node calculations/pin-map-export.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LCSC } from "./cost/lcsc-map.mjs";
import { footer, masthead } from "./doc-chrome.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
// physical: designator -> [{num,name}] from the apply payloads. The flat apply/ dir is the
// 30 kW set; the card, cabinet and 50kwa (superset: paralleled-pair parts) live per-target.
const phys = new Map(), mpnOf = new Map();
for (const dir of ["apply", "control-card/apply", "cabinet/apply", "50kwa/apply"]) {
  const APPLY = join(ROOT, "calculations/out/sheets", dir);
  for (const f of readdirSync(APPLY).filter((x) => x.endsWith(".json"))) {
    for (const c of JSON.parse(readFileSync(join(APPLY, f), "utf8")).chunks.flat()) {
      phys.set(c.designator, c.pins.map((p) => ({ num: String(p.pin_number), name: p.name })));
      mpnOf.set(c.designator, c.mpn || c.value);
    }
  }
}
// logical: designator -> [{num,name}] from the built netlist
const logi = new Map();
for (const path of ["30kw/acdc", "30kw/dcdc", "50kwa/acdc", "50kwa/dcdc", "control-card", "cabinet"]) {
  const j = JSON.parse(readFileSync(join(ROOT, "dist/boards", path, "circuit.json"), "utf8"));
  const nm = new Map(j.filter((e) => e.type === "source_component").map((c) => [c.source_component_id, c.name]));
  for (const p of j.filter((e) => e.type === "source_port")) {
    const d = nm.get(p.source_component_id);
    if (!logi.has(d)) logi.set(d, []);
    logi.get(d).push({ num: String(p.pin_number), name: p.name });
  }
}

// one row per part FAMILY (first designator that uses it)
const fams = new Map();
for (const [d, pins] of phys) {
  const m = mpnOf.get(d);
  if (!fams.has(m) && logi.has(d)) fams.set(m, { d, physical: pins, logical: logi.get(d) });
}

const rows = [], remapRows = [], sameRows = [];
for (const [m, v] of [...fams].sort()) {
  const lmap = new Map(v.logical.map((p) => [p.name, p.num]));
  const same = v.physical.every((p) => lmap.get(p.name) === p.num);
  const L = v.physical.map((p) => `${lmap.get(p.name) ?? "-"}=${p.name}`).join(" ");
  const P = v.physical.map((p) => `${p.num}=${p.name}`).join(" ");
  const lc = LCSC[m] ?? {};
  (same ? sameRows : remapRows).push(`| \`${m}\` | ${v.d} | ${same ? "_(same)_" : L} | ${P} | ${lc.lcsc ?? lc.status ?? ""} |`);
  for (const p of v.physical) rows.push([m, v.d, p.name, lmap.get(p.name) ?? "", p.num, lc.lcsc ?? lc.status ?? ""]);
}
const TH = "| Part | Example ref | Logical (as drawn) | Physical (as built) | LCSC |\n|---|---|---|---|---|";
const md = [masthead("docs/symbol-pin-map.md"), `
> [!NOTE]
> **Purpose** — the schematic cells are SKU-generic, so they use **logical** pin names (\`G\`/\`D\`/\`S\`/\`KS\` on a
> MOSFET, \`DST\`/\`ASC\`/\`RDY\` on a gate driver — the real vendor names since R4). Every netlist that leaves the
> repo passes through the remap in [\`sheet-netlist-gen.mjs\`](../calculations/sheet-netlist-gen.mjs), which turns
> those names into **physical package pins** from the manufacturer datasheet. **This page is that mapping.**
> Generated by \`calculations/pin-map-export.mjs\` — do not hand-edit.

| Part families | Families with a logical → physical remap | Pins mapped | Verification |
|---:|---:|---:|---|
| **${fams.size}** | **${remapRows.length}** | **${rows.length}** | \`kicad5-verify.mjs\` — 100 % pin-by-pin across the six SHIP targets |

> [!TIP]
> A drawing that shows logical numbering is not a pinout error — it is a drawing that has not applied this map.
> The KiCad sheets in \`kicad5/\` and the sheet payloads carry the physical numbering below.

## Families that carry a remap

${TH}
${remapRows.join("\n")}

## Families drawn with their physical numbering

<details><summary>${sameRows.length} families — logical and physical numbering are identical</summary>

${TH}
${sameRows.join("\n")}

</details>

${footer("docs/symbol-pin-map.md")}`];
writeFileSync(join(ROOT, "docs/symbol-pin-map.md"), md.join("\n") + "\n");
writeFileSync(join(ROOT, "calculations/out/symbol-pin-map.csv"),
  "part,example_ref,pin_name,logical_pin,physical_pin,lcsc\n" + rows.map((r) => r.join(",")).join("\n") + "\n");
console.log(`${fams.size} families · ${remapRows.length} remapped · ${rows.length} pins → docs/symbol-pin-map.md`);
